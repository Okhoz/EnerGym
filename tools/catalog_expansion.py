def entry(row):
	row = tuple(row)
	(id_, name, metric, goals, envs, resources, sports, coverage, alternatives, technique) = row
	return {
		"id": id_, "name": name, "metricType": metric, "goals": list(dict.fromkeys(goals)),
		"environments": envs, "requiredResources": resources, "sportIds": list(dict.fromkeys(sports)),
		"coverage": coverage, "reviewed": False, "description": technique + NOTE, "alternativeIds": alternatives,
	}


def main():
	catalog = json.loads(TARGETS[0].read_text(encoding="utf-8"))
	existing = {e["id"] for e in catalog["exercises"]}
	from catalog_more import MORE
	added = [entry(r) for r in EXERCISES + MORE if r[0] not in existing]
	catalog["exercises"].extend(added)
	ids = {e["id"] for e in catalog["exercises"]}
	sports = {s["id"]: s for s in catalog["sports"]}
	for e in catalog["exercises"]:
		assert len(e["id"]) <= 80, e["id"]
		for a in e["alternativeIds"]:
			assert a in ids and a != e["id"], (e["id"], a)
		for s in e["sportIds"]:
			key = "specificCoverage" if e["coverage"] == "SPECIFIC" else "complementaryCoverage"
			assert sports[s][key] != "PENDING_VALIDATION", (e["id"], s)
	assert len(ids) == len(catalog["exercises"]), "IDs duplicados"
	text = json.dumps(catalog, ensure_ascii=False, indent="\t") + "\n"
	for target in TARGETS:
		target.write_text(text, encoding="utf-8", newline="\n")
	print(f"{len(added)} ejercicios añadidos · total {len(catalog['exercises'])}")


if __name__ == "__main__":
	main()
